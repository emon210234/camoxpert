"""Build LaTeX tables from result JSON files. Numbers are never typed into the manuscript by hand.

    uv run python tools/make_tables.py --spec tables/main_table.json --out ../paper/tables/main.tex

Spec file (JSON):
{
  "caption_note": "single-pass, PySODMetrics",
  "mode": "single",                                   # reads eval_single.json (or "tta")
  "datasets": ["CAMO", "CHAMELEON", "COD10K", "NC4K"],
  "metrics":  ["Sm", "meanEm", "wFm", "MAE"],
  "digits": 3,
  "rows": [
    {"label": "ZoomNeXt-B5 (reported)", "external": "tables/external_results.json", "key": "ZoomNeXt-B5"},
    {"label": "ZoomNeXt-B5 (our pipeline)", "runs": ["C:/runs/R0_zoomnext_b5_s0"]},
    {"label": "CamoXpert", "runs": ["C:/runs/R5_camoxpert_s0", "C:/runs/R5_camoxpert_s1", "C:/runs/R5_camoxpert_s2"]}
  ]
}
* "runs": several run directories = several seeds -> the mean is shown (and "+-std" if
  "show_std": true in the spec). The number of runs is written to a comment in the .tex file.
* "external": numbers published by other papers, entered ONCE in a JSON file together with
  the citation key and the table/page they come from, e.g.
  {"ZoomNeXt-B5": {"cite": "pang2024zoomnext", "where": "GitHub README, PVTv2-B5 row",
                   "results": {"CAMO": {"Sm": 0.889, "wFm": 0.857, "MAE": 0.041}, ...}}}
  Missing values print as "--". Never mix in numbers measured under a different metric variant.
* Best value per column is bold, second best underlined (MAE: lower is better).
"""

import argparse
import json
import os
import statistics

LOWER_IS_BETTER = {"MAE"}
HEADERS = {
    "Sm": r"$S_\alpha\uparrow$",
    "wFm": r"$F_\beta^w\uparrow$",
    "MAE": r"$M\downarrow$",
    "meanEm": r"$E_\phi^{m}\uparrow$",
    "maxEm": r"$E_\phi^{x}\uparrow$",
    "adpEm": r"$E_\phi^{ad}\uparrow$",
    "meanFm": r"$F_\beta^{m}\uparrow$",
    "maxFm": r"$F_\beta^{x}\uparrow$",
    "adpFm": r"$F_\beta^{ad}\uparrow$",
}


def load_row(row, spec, base_dir):
    """-> {dataset: {metric: (mean, std or None, n)}}"""
    out = {}
    if "runs" in row:
        reports = []
        for r in row["runs"]:
            with open(os.path.join(r, f"eval_{spec['mode']}.json"), encoding="utf-8") as f:
                reports.append(json.load(f))
        for ds in spec["datasets"]:
            out[ds] = {}
            for m in spec["metrics"]:
                vals = [rep["results"][ds][m] for rep in reports]
                std = statistics.stdev(vals) if len(vals) > 1 else None
                out[ds][m] = (statistics.mean(vals), std, len(vals))
    else:
        path = row["external"] if os.path.isabs(row["external"]) else os.path.join(base_dir, row["external"])
        with open(path, encoding="utf-8") as f:
            ext = json.load(f)[row["key"]]["results"]
        for ds in spec["datasets"]:
            out[ds] = {m: ((ext.get(ds, {}).get(m)), None, 1) for m in spec["metrics"]}
    return out


def rank_marks(values, lower_better):
    """values: list of float or None -> list of '', 'best', 'second' (ties share the mark)."""
    present = sorted({v for v in values if v is not None}, reverse=not lower_better)
    marks = []
    for v in values:
        if v is None or not present:
            marks.append("")
        elif v == present[0]:
            marks.append("best")
        elif len(present) > 1 and v == present[1]:
            marks.append("second")
        else:
            marks.append("")
    return marks


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--spec", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()
    with open(args.spec, encoding="utf-8") as f:
        spec = json.load(f)
    base_dir = os.path.dirname(os.path.abspath(args.spec))
    digits = spec.get("digits", 3)
    rows = [load_row(r, spec, base_dir) for r in spec["rows"]]

    cols = [(ds, m) for ds in spec["datasets"] for m in spec["metrics"]]
    cells = [[""] * len(cols) for _ in rows]
    for j, (ds, m) in enumerate(cols):
        means = [None if r[ds][m][0] is None else round(r[ds][m][0], digits) for r in rows]
        marks = rank_marks(means, m in LOWER_IS_BETTER)
        for i, r in enumerate(rows):
            mean, std, _ = r[ds][m]
            if mean is None:
                cells[i][j] = "--"
                continue
            txt = f"{mean:.{digits}f}"
            if spec.get("show_std") and std is not None:
                txt += rf"{{\scriptsize$\pm${std:.{digits}f}}}"
            if marks[i] == "best":
                txt = rf"\textbf{{{txt}}}"
            elif marks[i] == "second":
                txt = rf"\underline{{{txt}}}"
            cells[i][j] = txt

    nm = len(spec["metrics"])
    lines = [
        f"% generated by tools/make_tables.py from {os.path.abspath(args.spec)} -- do not edit by hand",
        f"% mode: {spec['mode']}; {spec.get('caption_note', '')}",
    ]
    for r, row in zip(spec["rows"], rows):
        n = next(iter(row.values()))[spec["metrics"][0]][2]
        lines.append(f"% {r['label']}: " + (f"{n} run(s): {r['runs']}" if "runs" in r else f"external {r['key']}"))
    lines.append(r"\begin{tabular}{l" + ("c" * nm + "|") * (len(spec["datasets"]) - 1) + "c" * nm + "}")
    lines.append(r"\toprule")
    lines.append(" & " + " & ".join(rf"\multicolumn{{{nm}}}{{c}}{{{ds}}}" for ds in spec["datasets"]) + r" \\")
    lines.append("Method & " + " & ".join(HEADERS[m] for _, m in cols) + r" \\")
    lines.append(r"\midrule")
    for r, c in zip(spec["rows"], cells):
        lines.append(f"{r['label']} & " + " & ".join(c) + r" \\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
